/// Blends a foreground color over a background color using linear alpha interpolation.
#[inline]
pub fn blend_colors(fg: Color, bg: Color, alpha: u8) -> Color {
    let a = alpha as u32;
    let inv_a = 255 - a;

    let r = ((fg.r() as u32 * a + bg.r() as u32 * inv_a) / 255) as u8;
    let g = ((fg.g() as u32 * a + bg.g() as u32 * inv_a) / 255) as u8;
    let b = ((fg.b() as u32 * a + bg.b() as u32 * inv_a) / 255) as u8;

    Color::rgb(r, g, b)
}

/// High-resolution 32-bit TrueColor Canvas for in-memory drawing and double buffering.
pub struct Canvas {
    pub width: usize,
    pub height: usize,
    pub pixels: Vec<u32>,
}

impl Canvas {
    /// Creates a new Canvas initialized to solid black.
    pub fn new(width: usize, height: usize) -> Self {
        let size = width * height;
        Self {
            width,
            height,
            pixels: vec![0; size],
        }
    }

    /// Sets a pixel directly with bounds checking.
    #[inline]
    pub fn set_pixel(&mut self, x: usize, y: usize, color: Color) {
        if x < self.width && y < self.height {
            self.pixels[y * self.width + x] = color.0;
        }
    }

    /// Retrieves the pixel color at (x, y).
    #[inline]
    pub fn get_pixel(&self, x: usize, y: usize) -> Color {
        if x < self.width && y < self.height {
            Color(self.pixels[y * self.width + x])
        } else {
            Color::BLACK
        }
    }

    /// Blends a color over an existing pixel with alpha transparency (0 = fully transparent, 255 = fully opaque).
    #[inline]
    pub fn blend_pixel(&mut self, x: usize, y: usize, color: Color, alpha: u8) {
        if x < self.width && y < self.height {
            let bg = Color(self.pixels[y * self.width + x]);
            self.pixels[y * self.width + x] = blend_colors(color, bg, alpha).0;
        }
    }

    /// Clears the entire canvas with a solid color.
    pub fn clear(&mut self, color: Color) {
        self.pixels.fill(color.0);
    }

    /// Fills a solid rectangle.
    pub fn fill_rect(&mut self, x: usize, y: usize, w: usize, h: usize, color: Color) {
        let x_end = (x + w).min(self.width);
        let y_end = (y + h).min(self.height);

        for py in y..y_end {
            let row_offset = py * self.width;
            for px in x..x_end {
                self.pixels[row_offset + px] = color.0;
            }
        }
    }

    /// Fills a translucent rectangle with alpha blending (glassmorphism base).
    pub fn fill_rect_alpha(&mut self, x: usize, y: usize, w: usize, h: usize, color: Color, alpha: u8) {
        let x_end = (x + w).min(self.width);
        let y_end = (y + h).min(self.height);

        for py in y..y_end {
            for px in x..x_end {
                self.blend_pixel(px, py, color, alpha);
            }
        }
    }

    /// Draws a vertical linear gradient between two colors (used for wallpapers & titlebars).
    pub fn fill_gradient_v(&mut self, x: usize, y: usize, w: usize, h: usize, top: Color, bottom: Color) {
        let x_end = (x + w).min(self.width);
        let y_end = (y + h).min(self.height);
        if h == 0 {
            return;
        }

        for py in y..y_end {
            let factor = ((py - y) * 255) / h;
            let current = blend_colors(bottom, top, factor as u8);
            let row_offset = py * self.width;
            for px in x..x_end {
                self.pixels[row_offset + px] = current.0;
            }
        }
    }

    /// Fills a circle centered at (cx, cy) with the specified radius (used for macOS window buttons).
    pub fn fill_circle(&mut self, cx: isize, cy: isize, radius: isize, color: Color) {
        let r2 = radius * radius;
        let y_start = (cy - radius).max(0) as usize;
        let y_end = ((cy + radius + 1).min(self.height as isize)) as usize;

        for py in y_start..y_end {
            let dy = py as isize - cy;
            let dy2 = dy * dy;
            let dx_max = integer_sqrt((r2 - dy2).max(0) as usize) as isize;

            let x_start = (cx - dx_max).max(0) as usize;
            let x_end = ((cx + dx_max + 1).min(self.width as isize)) as usize;

            let row_offset = py * self.width;
            for px in x_start..x_end {
                self.pixels[row_offset + px] = color.0;
            }
        }
    }

    /// Fills a rounded rectangle with smooth corner curves (macOS signature aesthetic).
    pub fn fill_rounded_rect(&mut self, x: usize, y: usize, w: usize, h: usize, r: usize, color: Color) {
        if r == 0 {
            self.fill_rect(x, y, w, h, color);
            return;
        }

        let r_clamped = r.min(w / 2).min(h / 2);

        // 1. Center horizontal bar
        self.fill_rect(x, y + r_clamped, w, h - 2 * r_clamped, color);
        // 2. Top and bottom horizontal bars
        self.fill_rect(x + r_clamped, y, w - 2 * r_clamped, r_clamped, color);
        self.fill_rect(x + r_clamped, y + h - r_clamped, w - 2 * r_clamped, r_clamped, color);

        // 3. Four corner circles
        self.fill_circle((x + r_clamped) as isize, (y + r_clamped) as isize, r_clamped as isize, color);
        self.fill_circle((x + w - r_clamped - 1) as isize, (y + r_clamped) as isize, r_clamped as isize, color);
        self.fill_circle((x + r_clamped) as isize, (y + h - r_clamped - 1) as isize, r_clamped as isize, color);
        self.fill_circle((x + w - r_clamped - 1) as isize, (y + h - r_clamped - 1) as isize, r_clamped as isize, color);
    }

    /// Fills a rounded rectangle with translucency (used for the floating dock and menus).
    #[allow(clippy::too_many_arguments)]
    pub fn fill_rounded_rect_alpha(&mut self, x: usize, y: usize, w: usize, h: usize, r: usize, color: Color, alpha: u8) {
        let x_end = (x + w).min(self.width);
        let y_end = (y + h).min(self.height);
        let r_clamped = r.min(w / 2).min(h / 2);
        let r2 = (r_clamped * r_clamped) as isize;

        for py in y..y_end {
            for px in x..x_end {
                let in_top_left = px < x + r_clamped && py < y + r_clamped;
                let in_top_right = px >= x + w - r_clamped && py < y + r_clamped;
                let in_bot_left = px < x + r_clamped && py >= y + h - r_clamped;
                let in_bot_right = px >= x + w - r_clamped && py >= y + h - r_clamped;

                let mut inside = true;
                if in_top_left {
                    let dx = (px as isize) - (x + r_clamped) as isize;
                    let dy = (py as isize) - (y + r_clamped) as isize;
                    inside = dx * dx + dy * dy <= r2;
                } else if in_top_right {
                    let dx = (px as isize) - (x + w - r_clamped - 1) as isize;
                    let dy = (py as isize) - (y + r_clamped) as isize;
                    inside = dx * dx + dy * dy <= r2;
                } else if in_bot_left {
                    let dx = (px as isize) - (x + r_clamped) as isize;
                    let dy = (py as isize) - (y + h - r_clamped - 1) as isize;
                    inside = dx * dx + dy * dy <= r2;
                } else if in_bot_right {
                    let dx = (px as isize) - (x + w - r_clamped - 1) as isize;
                    let dy = (py as isize) - (y + h - r_clamped - 1) as isize;
                    inside = dx * dx + dy * dy <= r2;
                }

                if inside {
                    self.blend_pixel(px, py, color, alpha);
                }
            }
        }
    }

    /// Draws a 1-pixel rectangle outline.
    pub fn draw_rect_outline(&mut self, x: usize, y: usize, w: usize, h: usize, color: Color) {
        if w == 0 || h == 0 || self.width == 0 || self.height == 0 {
            return;
        }
        let x_end = (x + w - 1).min(self.width - 1);
        let y_end = (y + h - 1).min(self.height - 1);

        for px in x..=x_end {
            self.set_pixel(px, y, color);
            self.set_pixel(px, y_end, color);
        }
        for py in y..=y_end {
            self.set_pixel(x, py, color);
            self.set_pixel(x_end, py, color);
        }
    }

    /// Draws an ASCII character using the built-in 8x16 font glyph table.
    pub fn draw_char(&mut self, x: usize, y: usize, c: char, color: Color) {
        let glyph = get_glyph_8x16(c);
        for (row, &row_byte) in glyph.iter().enumerate() {
            for col in 0..8 {
                if (row_byte & (0x80 >> col)) != 0 {
                    self.set_pixel(x + col, y + row, color);
                }
            }
        }
    }

    /// Renders a text string at the specified coordinates.
    pub fn draw_string(&mut self, mut x: usize, y: usize, text: &str, color: Color) {
        for c in text.chars() {
            if c == '\n' {
                return;
            }
            self.draw_char(x, y, c, color);
            x += 8;
        }
    }
}

/// Fast integer square root without floating point instructions.
fn integer_sqrt(val: usize) -> usize {
    if val == 0 {
        return 0;
    }
    let mut x0 = val / 2;
    if x0 == 0 {
        return 1;
    }
    let mut x1 = (x0 + val / x0) / 2;
    while x1 < x0 {
        x0 = x1;
        x1 = (x0 + val / x0) / 2;
    }
    x0
}

